import nextEnv from "@next/env";
import { createClient } from "@supabase/supabase-js";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import assert from "node:assert/strict";
nextEnv.loadEnvConfig(process.cwd());
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.QA_PLAYWRIGHT_MODULE || "playwright");
const session = JSON.parse(await readFile(process.argv[2], "utf8"));
const account = session.accounts[0];
assert.match(account.email, /^sync-qa-.*@example\.test$/);
assert.ok(session.pageFitResumeId);
const client = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY,
  { auth: { persistSession: false, autoRefreshToken: false } });
const { error: authError } = await client.auth.signInWithPassword({ email: account.email, password: account.password });
if (authError) throw authError;
const row = await client.from("resumes").select("content").eq("id", session.pageFitResumeId).eq("user_id", account.id).single();
if (row.error) throw row.error;
const content = row.data.content;
assert.match(content.header.name, /^Alex Fitcheck/);
content.header.name = "Alex Fitcheck";
content.experience[0].description = Array.from({ length: 65 }, (_, i) => `Built synthetic service ${i + 1} with reliable APIs and measured test coverage for example workflows.`);
const seeded = await client.from("resumes").update({ content }).eq("id", session.pageFitResumeId).eq("user_id", account.id);
if (seeded.error) throw seeded.error;
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
  const errors = [], pdfRequests = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (new URL(request.url()).pathname === "/api/resume-pages") pdfRequests.push(request.url()); });
  await page.goto("http://localhost:3000/login", { waitUntil: "networkidle" });
  await page.getByLabel("Email", { exact: true }).fill(account.email);
  await page.getByLabel("Password", { exact: true }).fill(account.password);
  await page.getByRole("button", { name: "Login", exact: true }).click();
  await page.waitForURL(url => !url.pathname.startsWith("/login"));
  const responsePromise = page.waitForResponse(response => new URL(response.url()).pathname === "/api/resume-pages", { timeout: 60000 });
  await page.goto(`http://localhost:3000/resumes/${session.pageFitResumeId}`, { waitUntil: "domcontentloaded" });
  const response = await responsePromise;
  const result = await response.json();
  assert.equal(response.status(), 200, JSON.stringify(result));
  assert.ok(result.pages >= 2);
  assert.match(result.contentKey, /^[a-f0-9]{64}$/);
  const gauge = page.locator("p.text-2xl").filter({ hasText: `${result.pages} pages` });
  await gauge.waitFor({ timeout: 10000 }).catch(async error => {
    await writeFile("/tmp/resume-butler-auto-save-debug.txt", await page.locator("body").innerText());
    await page.screenshot({ path: "/tmp/resume-butler-auto-save-debug.png" });
    throw error;
  });
  assert.match(await gauge.getAttribute("class"), /text-red/);
  await page.screenshot({ path: "/tmp/resume-butler-auto-pdf.png" });
  const name = page.getByRole("textbox", { name: "Resume name", exact: true });
  const title = `QA Quiet Saving ${session.run} ${Date.now()}`;
  await name.fill(title);
  await page.getByRole("status").filter({ hasText: /\bSaving\b/ }).waitFor();
  await name.press("Tab");
  await page.getByRole("status").filter({ hasText: /\bSaved\b/ }).waitFor();
  await page.waitForLoadState("networkidle");
  assert.deepEqual(await page.locator("[data-sonner-toast]").allTextContents(), []);
  const saved = await client.from("resumes").select("title").eq("id", session.pageFitResumeId).eq("user_id", account.id).single();
  if (saved.error) throw saved.error;
  assert.equal(saved.data.title, title);
  assert.equal(pdfRequests.length, 1, "renaming must not recompile unchanged printed content");
  // A normal document edit also saves quietly, and immediately invalidates the old PDF count.
  const field = page.locator('.rb-name [contenteditable="true"], [contenteditable="true"].rb-name').first();
  await field.fill("Alex Fitcheck Updated");
  await field.press("Tab");
  await page.getByRole("status").filter({ hasText: /\bSaved\b/ }).waitFor();
  await page.waitForLoadState("networkidle");
  assert.deepEqual(await page.locator("[data-sonner-toast]").allTextContents(), []);
  assert.equal(pdfRequests.length, 1, "cooldown must defer compilation after another edit");
  await page.screenshot({ path: "/tmp/resume-butler-quiet-save.png" });
  assert.deepEqual(errors, []);
  const report = { autoPdfRequests: pdfRequests.length, actualPdfPages: result.pages, titlePersisted: true, ordinaryEditToasts: 0, pageErrors: errors };
  await writeFile("/tmp/resume-butler-auto-save-qa-result.json", JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally { await browser.close(); }
